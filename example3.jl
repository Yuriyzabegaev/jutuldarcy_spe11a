    linear_solver_arg=Dict(
        :amg_type => :hypre,
        :update_interval => :ministep,
        :partial_update => true,
        :update_interval_partial => :iteration,
        :nonlinear_relative_tolerance => 0.05,
        :relaxed_relative_tolerance => 0.1,
