end

# ## Parse the deck and inject facies-based properties
data = parse_data_file(deck_path)
n_cells = length(facies)
poro_full = [phi_tab[facies[c]] for c in 1:n_cells]
permx_full = [perm_mD[facies[c]] * mD for c in 1:n_cells]

data["GRID"]["PORO"] = poro_full
data["GRID"]["PERMX"] = permx_full
data["GRID"]["PERMY"] = permx_full
data["GRID"]["PERMZ"] = permx_full   # isotropic

# Build the full domain just to recover the SPE11a mesh geometry.
full_domain = reservoir_domain(data)
full_mesh = physical_representation(full_domain)

# ## Remove the sealing (zero-permeability) cells
# Following the SPE10 example, we drop the cells of the impermeable facies and
# extract a submesh containing only the active cells.
active = findall(facies .!= 7)
mesh = extract_submesh(full_mesh, active)

poro = poro_full[active]
perm = permx_full[active]
# Molecular diffusion per phase (SPE11a `diffusion` in input.toml): liquid 1e-9,
# gas 1.6e-5 [m^2/s]. The co2brine phases are ordered (LiquidPhase, VaporPhase),
# so row 1 = liquid, row 2 = gas. It must be given as an (nphase x ncell) matrix
# (one value per cell, per phase). Internally this becomes per-phase face
# diffusivities (D_alpha * porosity), adding Fickian component fluxes from
# gradients of the dissolved-CO2 / vaporized-H2O mass fractions.
diffusion = repeat([1e-9, 1.6e-5], 1, length(active))
domain = reservoir_domain(mesh, permeability=perm, porosity=poro, diffusion=diffusion)

# ## Locate the SPE11a injection cells
# SPE11a defines two injection locations. The pyopmspe11 deck places them at
# full-grid cells (i,j,k) = (91,1,101) (lower) and
# (180,1,43) (upper). We map these onto the active submesh (the seal cells were
# removed) by matching the logical (i,j,k) index, which `extract_submesh`
# preserves.
inj_ijk = [(91, 1, 101), (180, 1, 43)]
nc_full = number_of_cells(full_mesh)
inj_full = [findfirst(c -> cell_ijk(full_mesh, c) == ijk, 1:nc_full) for ijk in inj_ijk]
inj_cells = [searchsortedfirst(active, c) for c in inj_full]
well_radius = 9e-4   # SPE11a well bore radius [m] (input.toml `radius`)
injectors = [
    setup_well(domain, inj_cells[1], name=:Injector1, simple_well=true, radius=well_radius),
    setup_well(domain, inj_cells[2], name=:Injector2, simple_well=true, radius=well_radius),
]

# ## Miscible CO2-brine model with SPE11a constitutive laws
# The :co2brine model uses the CSP11/SPE11 H2O-CO2 property tables and K-values,
# so dissolved CO2 in brine and vaporized water in CO2 are represented.
domain[:temperature] = fill(20.0 + 273.15, number_of_cells(domain))
model = setup_reservoir_model(domain, :co2brine,
    wells=injectors,
    co2_physics=:kvalue,
    dz_max=0.05,
    dp_max_rel=0.1,
    fast_flash=true)

active_facies = facies[active]
# SPE11a capillary-pressure parameters per facies (input.toml `safu`): irreducible
# water saturation `swi` and entry pressure `pen` [Pa]. The generated deck clamps
# the erf capillary curve at penmax = 2500 Pa, but the benchmark description
# prescribes a maximum capillary pressure of 95000 Pa, so we recompute Pcgw
# analytically here rather than using the clamped deck values.
pc_swi = [0.32, 0.14, 0.12, 0.12, 0.12, 0.10, 0.0]
pc_pen = [1500.0, 300.0, 100.0, 25.0, 10.0, 1.0, 0.0]
penmax = 95000.0   # SPE11a maximum capillary pressure [Pa]
krw_tables = []
krg_tables = []
pcgw_tables = []
for (i, tab) in enumerate(sgwfn_tables)
    sg = tab[:, 1]
    krg = tab[:, 2]
    krw = tab[:, 3]
    swi, pen = pc_swi[i], pc_pen[i]
    pcgw = map(sg) do sg_i
        t = (1.0 - sg_i - swi) / (1.0 - swi)   # normalized effective water saturation
        t > 1e-10 ? penmax * erf(pen * t^(-0.5) * sqrt(π) / (2.0 * penmax)) : penmax
    end

    sw = reverse(1.0 .- sg)
    push!(krw_tables, PhaseRelativePermeability(sw, reverse(krw), label=:w))
    push!(krg_tables, PhaseRelativePermeability(sg, krg, label=:g))
    push!(pcgw_tables, get_1d_interpolator(sg, pcgw, constant_dx=false))
end

replace_variables!(model,
    RelativePermeabilities=RelativePermeabilities(
        (tuple(krw_tables...), tuple(krg_tables...)),
        regions=active_facies
    )
)
set_secondary_variables!(
    reservoir_model(model),
    CapillaryPressure=JutulDarcy.SimpleCapillaryPressure(
        (tuple(pcgw_tables...),),
        regions=active_facies
    )
)

# ## Initial state: domain initially contains hydrostatic brine
# SPE11a datum pressure is 1.1 bar (input.toml `pressure`), with the datum at the
# top of the rig; pressure increases hydrostatically with depth below it.
depth = domain[:cell_centroids][3, :]
p0 = 1.1 * bar .+ depth .* Jutul.gravity_constant .* 998.39   # 1.1 bar datum + hydrostatic
state0 = setup_reservoir_state(model, Pressure=p0, OverallMoleFractions=[1.0, 0.0])

# ## Time schedule (full SPE11a: 120 h)
# SPE11a injects for 5 h, then monitors up to a total of 120 h. Well 1 is active
# for the whole injection period while Well 2 only injects during its second half
# (2.5–5 h); both are shut for the post-injection monitoring phase. We use three
# force periods with report steps aligned at the 2.5 h and 5 h boundaries:
# 10-minute steps while injecting, 1-hour steps during monitoring.
dt_well1 = fill(10.0 * 60.0, 15)   # 0.0–2.5 h: Well 1 only
dt_both = fill(10.0 * 60.0, 15)    # 2.5–5.0 h: Well 1 + Well 2
dt_post = fill(1.0 * hour, 115)    # 5.0–120.0 h: post-injection monitoring
dt = vcat(dt_well1, dt_both, dt_post)
nstep = length(dt)

# ## Dirichlet (pressure) boundary condition on the top of the domain
# The top layer (k = 1) is the open free-flow boundary; the other three sides
# remain no-flow. The boundary transmissibility is computed automatically from the
# cell permeability and size with `dir = :z`.
top_cells = [c for c in 1:number_of_cells(mesh) if cell_ijk(mesh, c)[3] == 1]
p_bc = 1.115 * bar   # SPE11a free-flow BC (deck BCPROP: DIRICHLET WATER, 1.115 bar)
bc = flow_boundary_condition(top_cells, domain, p_bc; dir=:z, fractional_flow=[1.0, 0.0])

# ## Injection wells (SPE11a specification)
# Each single-perforation well injects pure CO2 at the SPE11a mass rate from
# `input.toml` (1.7e-7 kg/s each). A mass-rate target preserves the kg/s value
# directly. Well 1 injects for the whole 5 h; Well 2 only during the second half.
mass_rate = 1.7e-7 * kg
injector_control = InjectorControl(
    TotalMassRateTarget(mass_rate),
    [0.0, 1.0],
    density=2.0085 * kg / meter^3,
)
shut = DisabledControl()

forces_well1 = setup_reservoir_forces(model, bc=bc,
    control=Dict(:Injector1 => injector_control, :Injector2 => shut))
forces_both = setup_reservoir_forces(model, bc=bc,
    control=Dict(:Injector1 => injector_control, :Injector2 => injector_control))
forces_post = setup_reservoir_forces(model, bc=bc,
    control=Dict(:Injector1 => shut, :Injector2 => shut))

# One forces entry per report step, matching the three periods of the schedule.
forces = vcat(
    fill(forces_well1, length(dt_well1)),
    fill(forces_both, length(dt_both)),
    fill(forces_post, length(dt_post)),
)

parameters = setup_parameters(model)

