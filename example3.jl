# # 2D Two-Phase Flow on the SPE11a Geometry
# <tags: CO2, Compositional, Introduction>
# A simple two-phase miscible CO2-brine flow example that reuses the geometry,
# permeability and porosity of the SPE11a benchmark (a 2.8 m × 1.2 m vertical
# cross-section with 7 facies). The domain is initially fully saturated with a
# heavy liquid phase. A lighter vapor phase is injected from two point source
# terms — placed at the SPE11a injection cells — and rises towards the top
# under gravity.
#
# Three of the four boundaries are closed (no-flow, the JutulDarcy default).
# The top boundary is an open Dirichlet pressure boundary that lets the
# displaced fluids escape.
#
# The SPE11a deck (generated by pyopmspe11) contains a sealing facies with zero
# permeability. As in the SPE10 example, we remove these cells from the mesh
# rather than simulating through them — leaving them in would create isolated,
# non-flowing regions that hurt convergence.
#
# Generate the deck before running this script:
#   cd examples/workflow/spe11a_data && uv run pyopmspe11 -i input.toml -m deck -o output

using Jutul, JutulDarcy, GeoEnergyIO
using HYPRE
using GLMakie
using SpecialFunctions: erf

Darcy, bar, kg, meter, day = si_units(:darcy, :bar, :kilogram, :meter, :day)
mD = 1e-3 * Darcy
hour = 3600.0   # seconds

deck_dir = joinpath(@__DIR__, "spe11a_data", "output", "deck")
deck_path = joinpath(deck_dir, "OUTPUT.DATA")

# ## Parse the facies map from FLUXNUM.INC
# GeoEnergyIO does not support FLUXNUM or EQUALREG, so we parse the run-length
# encoded integer file directly to get one facies index per cell.
function parse_eclipse_rle_int(filepath)
    values = Int[]
    open(filepath) do f
        for line in eachline(f)
            line = split(strip(line), "--")[1]
            for token in split(line)
                token == "/" && return values
                if contains(token, "*")
                    n, v = split(token, "*")
                    append!(values, fill(parse(Int, v), parse(Int, n)))
                elseif all(c -> isdigit(c) || c == '-', token)
                    push!(values, parse(Int, token))
                end
            end
        end
    end
    return values
end

facies = parse_eclipse_rle_int(joinpath(deck_dir, "FLUXNUM.INC"))

# Permeability [mD] and porosity per facies (facies 7 is the sealing rock).
perm_mD = [44529.9988, 506624.985, 1013249.97, 2026499.95, 4052999.88, 10132499.7, 0.0]
phi_tab = [0.44, 0.43, 0.44, 0.45, 0.43, 0.46, 1e-6]

# ## Parse the SPE11a saturation-function tables
# The generated deck writes the benchmark constitutive laws in SGWFN as
# [Sg, krg, krw, pc] with pc in METRIC deck pressure units (bar).
function parse_sgwfn_tables(filepath)
    tables = Matrix{Float64}[]
    rows = Vector{Float64}[]
    in_sgwfn = false
    open(filepath) do f
        for line in eachline(f)
            line = strip(split(line, "--")[1])
            isempty(line) && continue
            for token in split(line)
                if token == "SGWFN"
                    in_sgwfn = true
                    continue
                end
                in_sgwfn || continue
                if token == "/"
                    if !isempty(rows)
                        push!(tables, reduce(vcat, transpose.(rows)))
                        empty!(rows)
                    end
                    continue
                end
                push!(rows, [parse(Float64, token)])
                if length(rows) >= 4 && all(length(r) == 1 for r in rows[end-3:end])
                    vals = vcat(rows[end-3:end]...)
                    resize!(rows, length(rows) - 4)
                    push!(rows, vals)
                end
            end
        end
    end
    return tables
end

sgwfn_tables = parse_sgwfn_tables(joinpath(deck_dir, "TABLES.INC"))

